def plot_point_cut(pms, pscans, out):
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.2), sharey=True)
    for ax, method in zip(axes, ("charge", "sum")):
        for key, pm in pms.items():
            rs = pscans[key][method]
            cuts = [r["cut"] for r in rs]
            line = None
            for name, ls in zip(pm.recos, ("--", "-", ":")):
                y = [r[name]["theta"] for r in rs]
                if name == pm.main:
                    line = ax.errorbar(cuts, y, yerr=[r["theta_err"] for r in rs], fmt="-", marker="o", ms=3,
                                       capsize=1.5, label=f"{pm.ds.short}, {name} reco")[0]

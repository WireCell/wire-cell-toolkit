'''
Make the generated parts of the SNB trigger tech note: figures (PDF),
tables (.tex) and named numbers (numbers.tex, used in the text as
\\res{key}).

    make_results.py --runs runs.json --out OUTDIR

runs.json (paths may be globs, relative to the runs.json file):

    {
      "version": "...",
      "sets": {
        "hd": {"files": "hd-v3/snb-*.npz", "label": "FD HD APA"},
        "vd": {"files": "vd-v3/snb-*.npz", "label": "FD VD top CRU", "short": "VD",
               "es_files": "vd-es/snb-*.npz"},  # optional ES sample
        ...                                  # optional extra sets
      },
      "display": {"dir": "display"},         # one-frame runs with depos and frames
      "marley": "marley-sample.json",        # a MARLEY JSON sample
      "methods": {                           # cuts in MeV of visible energy
        "charge": {"wp": 5.0, "scan": [...]},
        "sum": {"wp": 8.0, "seed": 1.0, "neighbor": 0.3, "radius_cm": 30,
                "scan": [...], "radii_cm": [...]}
      },
      "block_us": 200,
      "module_kt": 14,
      "pointing": {                          # see trig/pytools/snbpoint.py
        "burst_s": 10,                       # SNB reference rate x this = events
        "cc_xs": 0.2007,                     # MARLEY flux averaged, 1e-40 cm2
        "es": {"ve": [0.01833, 11, 1], ...}, # flavor: [xs, mean E, multiplicity]
        "reco": {"ideal": {}, "nominal": {"sigma10_deg": 25, "p_flip": 0.2}},
        "main": "nominal"
      }
    }

Sets give their CC sample (files) and optionally an ES sample (es_files), both
with the MARLEY summaries of run-snb-ta-study.sh next to the .npz files.

Requires numpy and matplotlib.
'''


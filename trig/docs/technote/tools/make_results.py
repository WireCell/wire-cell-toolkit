class Numbers:
    '''Named results for the text: \\res{key}.'''

    def __init__(self):
        self.vals = {}

    def __setitem__(self, key, val):
        self.vals[key] = val

    def write(self, path):
        with open(path, "w") as fp:
            fp.write("% generated by make_results.py\n")
            for key, val in sorted(self.vals.items()):
                fp.write("\\expandafter\\def\\csname res@%s\\endcsname{%s}\n" % (key, val))


def fmt(x, digits=3):
    if x is None or (isinstance(x, float) and not numpy.isfinite(x)):
        return "--"
    if x == 0:
        return "0"
    ax = abs(x)
    if 1e-3 <= ax < 1e5:
        return f"{x:.{digits}g}"
    mant, exp = f"{x:.{digits - 1}e}".split("e")
    return f"\\ensuremath{{{mant}\\times10^{{{int(exp)}}}}}"


def fmt_rate(r, limit=None):
    if limit is not None and numpy.isfinite(limit):
        return f"$<${fmt(limit, 2)}"
    return fmt(r)


def purity_text(r):
    """Purity, or its lower bound when no background passed."""
    if r["n_background"]:
        return fmt(r["purity"])
    sig = r["rate_signal_hz"]
    rel = r["rate_snb_related_hz"]
    return "$>$" + fmt(sig / (rel + r["rate_background_limit_hz"]), 2) if rel > 0 else "--"


def fmt_bytes(bps):
    for unit, scale in (("TB/s", 1e12), ("GB/s", 1e9), ("MB/s", 1e6), ("kB/s", 1e3)):
        if bps >= scale:
            return f"{bps/scale:.3g}~{unit}"
    return f"{bps:.3g}~B/s"


def savefig(fig, out, name):
    fig.savefig(os.path.join(out, name + ".pdf"))
    plt.close(fig)


def load_tar(path):
    out = {}
    with tarfile.open(path) as tf:
        for m in tf.getmembers():
            out[m.name] = numpy.load(io.BytesIO(tf.extractfile(m).read()))
    return out


def run_files(base, pattern):
    """The TATruth outputs matching pattern, less the MARLEY summaries."""
    return [f for f in sorted(glob.glob(os.path.join(base, pattern))) if not f.endswith("-marley.npz")]


class Set:
    '''A run set with its study and its methods evaluated.'''

    def __init__(self, key, cfg, base, methods, block, module_kt):
        self.key = key
        self.label = cfg.get("label", key)
        self.short = cfg.get("short", key.upper())
        files = run_files(base, cfg["files"])
        if not files:
            raise FileNotFoundError(cfg["files"])
        self.st = snbta.Study(files)
        self.k = self.st.adc_per_mev()  # ADC per MeV visible
        self.block = block
        self.module = module_kt * 1e6 / self.st.mass_kg
        self.methods = methods
        sm = methods["sum"]
        self.radius = sm.get("radius_cm", 30) * cm
        self.sums = self.st.neighborhood_sum(radius=self.radius, neighbor=sm["neighbor"] * self.k)
        # an ES sample, selected with the same cuts in visible MeV (this
        # set's calibration)
        self.es = None
        esfiles = run_files(base, cfg["es_files"]) if "es_files" in cfg else []
        if esfiles:
            self.es = snbta.Study(esfiles)
            self.es_sums = self.es.neighborhood_sum(radius=self.radius, neighbor=sm["neighbor"] * self.k)

    def select_es(self, method, mev):
        """The selection on the ES sample."""
        if method == "charge":
            return self.es.charge_selection(mev * self.k)
        return self.es.sum_selection(mev * self.k, self.methods["sum"]["seed"] * self.k, self.es_sums)

    def charge(self, mev):
        return self.st.charge_selection(mev * self.k)

    def sum(self, mev, sums=None, seed=None):
        sm = self.methods["sum"]
        seed = sm["seed"] if seed is None else seed
        return self.st.sum_selection(mev * self.k, seed * self.k, self.sums if sums is None else sums)

    def metrics(self, sel, relaxed=None):
        return self.st.metrics(sel, block=self.block, relaxed=relaxed)

    def select(self, method, mev, sums=None):
        """(selection, the same at half the cut)."""
        if method == "charge":
            return self.charge(mev), self.charge(0.5 * mev)
        return self.sum(mev, sums=sums), self.sum(0.5 * mev, sums=sums)

    def evaluate(self, method, mev, sums=None, block=None):
        sel, rel = self.select(method, mev, sums)
        return self.st.metrics(sel, block=self.block if block is None else block, relaxed=rel)


def detector_numbers(sets, display, num, out):
    '''Noise, thresholds and calibration from the display frames.'''
    rows = []
    for key, ds in sets.items():
        st = ds.st
        det = st.detector
        noise = [float("nan")] * 3
        if display:
            path = os.path.join(display, f"frames-{det}.tar.bz2")
            if os.path.exists(path):
                f = load_tar(path)
                fr = [v for k, v in f.items() if k.startswith("frame_")][0].astype(float)
                med = numpy.median(fr, axis=1)
                mad = numpy.median(numpy.abs(fr - med[:, None]), axis=1) * 1.4826
                chans = [v for k, v in f.items() if k.startswith("channels_")][0]
                tframes = snbta.load([os.path.join(display, f"truth-{det}.npz")])[3]
                pc = tframes[0].get("plane_channels")
                if pc:
                    noise = [float(numpy.median(mad[numpy.isin(chans, pc[p])])) for p in range(3)]

        thr = st.meta["thresholds"]
        num[f"{key}.mass"] = f"{st.mass_kg/1000:.1f}"
        num[f"{key}.nch"] = f"{st.nchannels}"
        num[f"{key}.adcbits"] = f"{st.meta.get('adc_resolution', 14)}"
        num[f"{key}.adcpermev"] = f"{ds.k:.0f}"
        num[f"{key}.lifetime"] = f"{st.meta.get('lifetime', 8*ms)/ms:.0f}"
        num[f"{key}.module"] = f"{ds.module:.0f}"
        bps = st.meta.get("adc_resolution", 14) / 8.0
        num[f"{key}.bytespersample"] = f"{bps:g}"
        num[f"{key}.blockvolume"] = fmt_bytes(st.nchannels * (ds.block / st.tick) * bps).replace("/s", "")
        num[f"{key}.boost"] = f"{st.boost:.0f}"
        num[f"{key}.snbphys"] = f"{st.snb_physical_rate_hz:.2f}"
        num[f"{key}.snbsim"] = f"{st.snb_rate_hz:g}"
        num[f"{key}.nframes"] = f"{st.nframes}"
        num[f"{key}.live"] = f"{st.live:.1f}"
        num[f"{key}.nvisible"] = f"{st.visible.sum()}"
        for p, name in enumerate("uvw"):
            num[f"{key}.noise{name}"] = f"{noise[p]:.1f}"
            num[f"{key}.thr{name}"] = f"{thr[p]}"
            num[f"{key}.thrsigma{name}"] = f"{thr[p]/noise[p]:.1f}" if numpy.isfinite(noise[p]) else "--"
        rows.append((ds, noise, thr))

    with open(os.path.join(out, "tab-detectors.tex"), "w") as fp:
        fp.write("\\begin{tabular}{l" + "r" * len(rows) + "}\n\\toprule\n")
        fp.write(" & " + " & ".join(ds.short for ds, _, _ in rows) + " \\\\\n\\midrule\n")

        def line(name, vals):
            fp.write(name + " & " + " & ".join(vals) + " \\\\\n")
        line("geometry", [short_geometry(ds.st.meta.get("geometry", ds.key)) for ds, _, _ in rows])
        line("argon mass [t]", [f"{ds.st.mass_kg/1000:.1f}" for ds, _, _ in rows])
        line("channels", [f"{ds.st.nchannels}" for ds, _, _ in rows])
        line("ADC bits", [f"{ds.st.meta.get('adc_resolution', 14)}" for ds, _, _ in rows])
        line("electron lifetime [ms]", [f"{ds.st.meta.get('lifetime', 8*ms)/ms:.0f}" for ds, _, _ in rows])
        line("noise RMS U/V/W [ADC]", ["/".join(f"{x:.1f}" for x in nz) for _, nz, _ in rows])
        line("TP threshold U/V/W [ADC]", ["/".join(f"{x}" for x in thr) for _, _, thr in rows])
        line("threshold / noise (W)", [f"{thr[2]/nz[2]:.1f}" for _, nz, thr in rows])
        line("ADC per visible MeV (W)", [f"{ds.k:.0f}" for ds, _, _ in rows])
        line("units per 14~kt active", [f"{ds.module:.0f}" for ds, _, _ in rows])
        fp.write("\\bottomrule\n\\end{tabular}\n")


def short_geometry(geom):
    """A compact geometry cell, eg "1x2x6 APA 0", "v6 top CRU 160"."""
    for long, short in (("DUNE FD HD ", ""), ("DUNE FD VD ", ""), (",", ""), ("bottom", "bot.")):
        geom = geom.replace(long, short)
    return geom.replace("_", "\\_")


def source_table(sets, num, out):
    '''Sources: activity, rate per unit, boost, count.'''
    st0 = list(sets.values())[0].st
    names = st0.source_names
    with open(os.path.join(out, "tab-sources.tex"), "w") as fp:
        cols = "l" + "rrr" * len(sets)
        fp.write("\\begin{tabular}{" + cols + "}\n\\toprule\n")
        fp.write(" & " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{ds.label}}}" for ds in sets.values())
                 + " \\\\\n")
        fp.write("source" + " & rate [Hz] & boost & simulated" * len(sets) + " \\\\\n\\midrule\n")
        for i, name in enumerate(names):
            vals = []
            for ds in sets.values():
                st = ds.st
                if name not in st.source_names:
                    vals += ["--"] * 3
                    continue
                j = st.source_names.index(name)
                nsim = (st.int_source == j).sum()
                # physical rate in the unit from the simulated count
                rate = nsim / (st.nframes * st.gen_span / snbta.s) / st.source_boost[j]
                vals += [fmt(rate), f"{st.source_boost[j]:.0f}", f"{nsim}"]
            fp.write(name + " & " + " & ".join(vals) + " \\\\\n")
        fp.write("\\bottomrule\n\\end{tabular}\n")


def scan(ds, method, cuts):
    out = []
    for c in cuts:
        r = ds.evaluate(method, c)
        r["cut"] = c
        out.append(r)
    return out


def plot_roc(sets, scans, out):
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.2), sharey=True)
    for ax, what, xlabel in ((axes[0], "rate_background_hz", "background TA rate per unit [Hz]"),
                             (axes[1], "data_background_Bps", "steady-state data rate per unit [B/s]")):
        for key, ds in sets.items():
            for method, ls in (("charge", "--"), ("sum", "-")):
                rs = scans[key][method]
                x = numpy.array([max(r[what], 1e-3 if what.startswith("rate") else 1e3) for r in rs])
                y = numpy.array([r["efficiency"] for r in rs])
                limited = numpy.array([r["n_background"] == 0 for r in rs])
                line, = ax.plot(x[~limited], y[~limited], ls, marker="o", ms=3, label=f"{ds.label}, {method}")
                if limited.any() and what == "rate_background_hz":
                    xl = numpy.array([r["rate_background_limit_hz"] for r in rs])[limited]
                    ax.plot(xl, y[limited], "<", color=line.get_color(), ms=4)
        ax.set_xscale("log")
        ax.set_xlabel(xlabel)
    axes[0].set_ylabel("SNB interaction efficiency")
    axes[0].legend(loc="lower right")
    axes[0].set_ylim(0.3, 1.01)
    savefig(fig, out, "fig-roc")



def tpg_channel(adc, threshold, accum_limit=10):
    '''The trig TPGChannel (mode pedestal, frugal median, no filter) in
    numpy: the pedestal per sample and the TPs as (start, samples over
    threshold, samples to peak, peak, integral).'''
    vals, counts = numpy.unique(adc, return_counts=True)
    ped, accum = int(vals[numpy.argmax(counts)]), 0
    peds = numpy.zeros(len(adc), dtype=int)
    tps, start = [], None
    for i, x in enumerate(adc.astype(int).tolist()):
        accum += (x > ped) - (x < ped)
        if accum > accum_limit:
            ped, accum = ped + 1, 0
        elif accum < -accum_limit:
            ped, accum = ped - 1, 0
        peds[i] = ped
        s = x - ped
        if s > threshold and start is None:
            start = i
        elif s <= threshold and start is not None:
            seg = adc[start:i].astype(int) - peds[start:i]
            tps.append((start, i - start, int(numpy.argmax(seg)), int(seg.max()), int(seg.sum())))
            start = None
    return peds, tps



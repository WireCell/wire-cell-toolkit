class PointingModel:
    '''The pointing proxy of a set, for a burst at the reference rate in a
    module (module_kt of active argon).'''

    def __init__(self, ds, pcfg, module_kt, nboot=20):
        self.ds = ds
        st = ds.st
        ref = st.meta.get("snb_physical_rate_hz_per_t", 0.0075)
        self.count_cc = ref * pcfg.get("burst_s", 10) * module_kt * 1000
        self.es_per_cc = snbpoint.es_per_cc(pcfg["cc_xs"], {k: tuple(v) for k, v in pcfg["es"].items()})
        self.count_es = self.count_cc * self.es_per_cc
        self.recos = list(pcfg["reco"])
        self.main = pcfg.get("main", self.recos[-1])
        kcc = snbpoint.Kinematics(st)
        kes = snbpoint.Kinematics(ds.es) if ds.es is not None else None
        self.cc = {n: snbpoint.Pointing(st, kcc, snbpoint.Reco(**rc)) for n, rc in pcfg["reco"].items()}
        self.es = {n: snbpoint.Pointing(ds.es, kes, snbpoint.Reco(**rc)) for n, rc in pcfg["reco"].items()} \
            if kes is not None else {}
        rng = numpy.random.default_rng(12345)
        self.boot_cc = rng.poisson(1.0, size=(nboot, len(st.ints["id"])))
        self.boot_es = rng.poisson(1.0, size=(nboot, len(ds.es.ints["id"]))) if kes is not None else None

    def evaluate(self, method, mev):
        ds = self.ds
        sel, _ = ds.select(method, mev)
        fcc = ds.st.found(sel)
        fes = ds.es.found(ds.select_es(method, mev)) if self.es else None
        r = dict(cut=mev, eff_cc=self.cc[self.main].efficiency(fcc, snbpoint.CC),
                 eff_es=self.es[self.main].efficiency(fes, snbpoint.ES) if self.es else float("nan"))
        for name in self.recos:
            icc = self.cc[name].information(fcc, self.count_cc, snbpoint.CC)
            ies = self.es[name].information(fes, self.count_es, snbpoint.ES) if self.es else 0.0
            r[name] = dict(info_cc=icc, info_es=ies, theta=snbpoint.theta68_deg(icc + ies),
                           theta_cc=snbpoint.theta68_deg(icc), theta_es=snbpoint.theta68_deg(ies))
        # bootstrap spread of the main proxy
        thetas = []
        for b in range(len(self.boot_cc)):
            icc = self.cc[self.main].information(fcc, self.count_cc, snbpoint.CC, self.boot_cc[b])
            ies = self.es[self.main].information(fes, self.count_es, snbpoint.ES, self.boot_es[b]) \
                if self.es else 0.0
            thetas.append(snbpoint.theta68_deg(icc + ies))
        r["theta_err"] = float(numpy.std(thetas))
        return r


def pointing_scan(pm, method, cuts):
    return [pm.evaluate(method, c) for c in cuts]



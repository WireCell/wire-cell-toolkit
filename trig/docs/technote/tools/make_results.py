def plot_ta_energy(sets, out):
    '''Visible energy of collection TAs by source, at physical rates.'''
    fig, axes = plt.subplots(1, len(sets), figsize=(3.6 * len(sets), 3.2), sharey=True, squeeze=False)
    bins = numpy.logspace(-2, 2, 61)
    for ax, (key, ds) in zip(axes[0], sets.items()):
        st = ds.st
        t = st.tas
        c = t["plane"] == 2
        e = t["adc_integral"] / ds.k
        w = 1.0 / st.ta_boost / st.live
        groups = {}
        for i, name in enumerate(st.source_names):
            m = c & (st.ta_source == i) & (st.ta_snb == (name == "snb"))
            if name == "snb":
                m = c & st.ta_snb
            if m.any():
                groups[name + (" (stress)" if name in st.stress else "")] = m
        m = c & (st.ta_source < 0)
        if m.any():
            groups["noise"] = m
        for name, m in groups.items():
            ax.hist(e[m], bins=bins, weights=w[m], histtype="step", lw=1.2,
                    color=SOURCE_COLORS.get(name.split()[0], "k"), label=name)
        ax.set_xscale("log")
        ax.set_yscale("log")
        ax.set_xlabel("TA visible energy [MeV]")
        ax.set_title(ds.label, fontsize=9)
        ax.axvline(ds.methods["charge"]["wp"], color="k", ls=":", lw=1)
    axes[0][0].set_ylabel("collection TAs per unit [Hz / bin]")
    axes[0][-1].legend(loc="upper right", ncol=2)
    savefig(fig, out, "fig-ta-energy")


def plot_sum_energy(sets, out):
    '''Neighborhood sums for seed TAs: signal vs background.'''
    fig, axes = plt.subplots(1, len(sets), figsize=(3.6 * len(sets), 3.2), sharey=True, squeeze=False)
    bins = numpy.linspace(0, 40, 81)
    for ax, (key, ds) in zip(axes[0], sets.items()):
        st = ds.st
        t = st.tas
        seed = (t["plane"] == 2) & (t["adc_integral"] >= ds.methods["sum"]["seed"] * ds.k)
        e = ds.sums / ds.k
        w = 1.0 / st.ta_boost / st.live
        sig = seed & st.ta_signal
        ax.hist(e[sig], bins=bins, weights=w[sig], histtype="step", lw=1.4, color=SOURCE_COLORS["snb"],
                label="SNB (physical rate)")
        for i, name in enumerate(st.source_names):
            m = seed & ~st.ta_snb & (st.ta_source == i)
            if m.any() and name != "snb":
                ax.hist(e[m], bins=bins, weights=w[m], histtype="step", lw=1.0,
                        color=SOURCE_COLORS.get(name, "k"),
                        label=name + (" (stress, arbitrary rate)" if name in st.stress else ""))
        ax.set_yscale("log")
        ax.set_xlabel("neighborhood sum [MeV visible]")
        ax.set_title(ds.label, fontsize=9)
        ax.axvline(ds.methods["sum"]["wp"], color="k", ls=":", lw=1)
    axes[0][0].set_ylabel("seed TAs per unit [Hz / bin]")
    axes[0][-1].legend(loc="upper right")
    savefig(fig, out, "fig-sum-energy")


def plot_tas_per_interaction(sets, out):
    fig, ax = plt.subplots()
    for key, ds in sets.items():
        st = ds.st
        t = st.tas
        good = st.link_dominant & (st.link_int >= 0) & (t["plane"][st.link_ta] == 2)

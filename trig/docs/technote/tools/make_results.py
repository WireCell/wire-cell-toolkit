def plot_pass(sets, scans, out):
    '''Per-decay pass probabilities of the MeV-scale sources.'''
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.2), sharey=True)
    key = list(sets)[0]
    for ax, method in zip(axes, ("charge", "sum")):
        for key, ds in sets.items():
            rs = scans[key][method]
            cuts = [r["cut"] for r in rs]
            for name, ls in (("K42", "-"), ("Bi214", "--"), ("nCapture", ":")):
                if name not in ds.st.source_names:
                    continue
                y = [r["pass_probability"][name] for r in rs]
                ax.plot(cuts, numpy.maximum(y, 1e-5), ls, marker="o", ms=2.5,
                        color=SOURCE_COLORS[name] if key == list(sets)[0] else None,
                        label=f"{ds.label}: {name}")
        ax.set_yscale("log")
        ax.set_ylim(5e-5, 2)
        ax.set_xlabel(("single-TA" if method == "charge" else "neighborhood sum") + " cut [MeV visible]")
    axes[0].set_ylabel("pass probability per decay")
    axes[1].legend(fontsize=6.5)
    savefig(fig, out, "fig-pass")


def plot_radius(sets, out, radii):
    fig, ax = plt.subplots()
    ax2 = ax.twinx()
    for key, ds in sets.items():
        effs, bkgs = [], []
        for r in radii:
            sums = ds.st.neighborhood_sum(radius=r * cm, neighbor=ds.methods["sum"]["neighbor"] * ds.k)
            m = ds.evaluate("sum", ds.methods["sum"]["wp"], sums=sums)
            effs.append(m["efficiency"])
            bkgs.append(m["rate_background_hz"] if m["n_background"] else m["rate_background_limit_hz"])
        ax.plot(radii, effs, "-o", ms=3, label=f"{ds.label} efficiency")
        ax2.plot(radii, bkgs, "--s", ms=3, label=f"{ds.label} background")
    ax.set_xlabel("neighborhood radius [cm]")
    ax.set_ylabel("efficiency (solid)")
    ax2.set_ylabel("background TA rate [Hz] (dashed)")
    ax2.set_yscale("log")
    ax.legend(loc="lower right")
    savefig(fig, out, "fig-radius")


def plot_block(sets, out, lengths=(25, 50, 100, 150, 200, 300, 400), cuts=None):
    """Data rate per unit against the block length: steady state at cuts
    that leave background, and during a burst at the working points."""
    cuts = cuts or {"charge": [1.0, 3.0], "sum": [3.0, 4.0]}
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 3.2))
    for key, ds in sets.items():
        for method, ls in (("charge", "--"), ("sum", "-")):
            for c in cuts[method]:
                y = [ds.evaluate(method, c, block=L * us)["data_background_Bps"] for L in lengths]

def plot_tc_example(out, window=8.0, threshold=6, holdoff=None):
    '''The burst TC algorithm on a made-up TA sequence.'''
    rng = numpy.random.default_rng(3)
    bkg = numpy.sort(rng.uniform(0, 40, 14))
    burst = numpy.sort(16 + rng.exponential(2.5, 9))
    tsel = numpy.sort(numpy.concatenate([bkg, burst]))
    trej = numpy.sort(rng.uniform(0, 40, 18))
    late = burst[4] + 0.0  # arrives after later ones were processed
    holdoff = window if holdoff is None else holdoff
    # the window count after each selected TA and the TCs, as TCMakerBurst
    count_t, count_n, tcs, armed = [0.0], [0], [], -numpy.inf
    for i, head in enumerate(tsel):
        n = ((tsel[:i + 1] > head - window)).sum()
        count_t.append(head)
        count_n.append(n)
        if n >= threshold and head >= armed:
            tcs.append(head)
            armed = head + holdoff
    fig, axes = plt.subplots(2, 1, figsize=(6.4, 3.6), sharex=True, gridspec_kw=dict(height_ratios=(1, 1.6)))
    ax = axes[0]
    ax.vlines(trej, 0.1, 0.9, color="0.7", lw=1, label="TA failing the selection")
    ax.vlines(tsel, 1.1, 1.9, color="#1f77b4", lw=1.5, label="selected TA")
    ax.plot([late], [2.05], "v", color="#ff7f0e", ms=5, label="a late TA, counted where it starts")
    tc = tcs[0]
    ax.add_patch(Rectangle((tc - window, 1.0), window, 1.0, fill=False, ec="#2ca02c", lw=1.2, ls="--"))
    ax.annotate("sliding window $W$", xy=(tc - window / 2, 2.0), xytext=(tc - window / 2, 2.6),
                ha="center", fontsize=7, color="#2ca02c")
    ax.set_ylim(0, 3.0)
    ax.set_yticks([])
    ax.grid(False)
    ax.legend(loc="upper left", fontsize=6, ncol=3, bbox_to_anchor=(0, 1.32))
    ax = axes[1]
    ax.step(count_t + [40], count_n + [count_n[-1]], where="post", color="#1f77b4", lw=1.2,
            label="selected TAs in the window, at each selected TA")
    ax.axhline(threshold, color="#d62728", ls="--", lw=1, label=f"threshold $N$ = {threshold}")
    for i, tc in enumerate(tcs):
        ax.axvline(tc, color="#2ca02c", lw=1.2)
        ax.axvspan(tc, tc + holdoff, color="#2ca02c", alpha=0.12, lw=0,
                   label="hold-off (no new TC)" if i == 0 else None)
        ax.annotate("TC", xy=(tc, 0.5), xytext=(3, 0), textcoords="offset points",
                    color="#2ca02c", fontsize=8)
    ax.set_ylim(0, max(count_n) + 2)
    ax.set_xlim(0, 40)
    ax.set_ylabel("count")
    ax.set_xlabel("TA start time [arbitrary units]")
    ax.legend(loc="upper right", fontsize=6)
    savefig(fig, out, "fig-tc-example")


